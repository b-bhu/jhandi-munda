#!/usr/bin/env python3
"""Scopes docs/design/app-html/app.css under `.app` and writes app/styles/app-mock.css.

The mock's class names (.panel, .row, .dice, .stats, .proof ...) would collide with the landing page
and the shell, so every rule is prefixed with `.app `. Rules for the mock's own header, nav and footer
(.top, .nav, .pill, .shellbanner, .foot) are dropped: the real shell has its own.
Run:  python3 scripts/scope-mock-css.py
"""
import re, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
src = (root / "docs/design/app-html/app.css").read_text()
DROP = re.compile(r"^\.(top|nav|pill|shellbanner|foot)\b")

def split_rules(css):
    out, depth, cur = [], 0, ""
    for ch in css:
        cur += ch
        if ch == "{": depth += 1
        elif ch == "}":
            depth -= 1
            if depth == 0: out.append(cur.strip()); cur = ""
    return out

def scope_selector(sel):
    sel = sel.strip()
    if DROP.match(sel): return None
    if sel == ".page": return ".app"
    return ".app " + sel

def scope_block(rule):
    head, body = rule.split("{", 1)
    body = body.rsplit("}", 1)[0]
    if head.startswith("@media"):
        inner = [scope_block(r) for r in split_rules(body)]
        inner = [r for r in inner if r]
        return head.strip() + "{\n" + "\n".join("  " + r for r in inner) + "\n}" if inner else None
    sels = [scope_selector(s) for s in head.split(",")]
    sels = [s for s in sels if s]
    if not sels: return None
    return ", ".join(sels) + " {" + body.strip() + "}"

rules = [scope_block(r) for r in split_rules(src)]
css = "\n".join(r for r in rules if r)
css = css.replace("url(img/bowl-crop.jpg)", "url(/img/bowl-crop.webp)")
header = "/* GENERATED by scripts/scope-mock-css.py from docs/design/app-html/app.css. Do not edit by hand. */\n"
(root / "app/styles/app-mock.css").write_text(header + css + "\n")
print(f"wrote app/styles/app-mock.css: {len(rules)} rules in, {sum(1 for r in rules if r)} out")
